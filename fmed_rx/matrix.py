"""医保风控矩阵：时间轴(事前/事中/事后) × 对象轴(医院/医师/患者/药品/物流)。

核心设计约束（对标方案未显式表述，但缺之即错）：

  **证据门槛随时间轴前移而升高。**
  事前拦截发生在治疗之前，误拦阻断的是正当治疗，不可逆；
  事后追回发生在支付之后，误判只多一轮复核，钱可追回。
  因此 threshold(事前) > threshold(事中) > threshold(事后)。
  对三个时点使用同一阈值，等于把不可逆风险和可逆风险同价处理。

  **单元格的可行性由数据时延决定，不由算法决定。**
  事前只有处方与参保人历史可用，结算明细尚未产生；
  医患共谋这类需要跨人群共现网络的模型在事前不可用——
  把事后模型搬到事前，得到的是高假阳性，不是早期干预。
"""
from __future__ import annotations

STAGES = ("事前", "事中", "事后")
OBJECTS = ("医院", "医师", "患者", "药品", "物流")

# 证据门槛梯度：误拒代价越高，要求证据越强
# 数值为"触发干预所需的最低证据等级"，1=统计异常，2=规则硬命中，3=规则硬命中+人工复核
THRESHOLD = {"事前": 3, "事中": 2, "事后": 1}

# 可逆性：决定允许的最强干预
REVERSIBILITY = {
    "事前": "不可逆-阻断治疗",
    "事中": "部分可逆-可当场纠正",
    "事后": "可逆-资金可追回",
}

MATRIX = {
 ("事前","医院"): dict(信号=["机构既往违规史","同病组费用结构偏离"],
                       干预=["提高抽审比例"], 可用性="可用",
                       备注="机构级，不触及个案治疗，误判代价低"),
 ("事前","医师"): dict(信号=["开方集中度","既往超量/超适应症记录"],
                       干预=["开方前提示"], 可用性="可用",
                       备注="仅提示，不得阻断"),
 ("事前","患者"): dict(信号=["跨机构重复购药","短周期购药量"],
                       干预=["限制开药量","引导线下就诊"], 可用性="可用",
                       备注="须留申诉通道；慢病患者正常续方极易被误判"),
 ("事前","药品"): dict(信号=["说明书每日最大剂量","目录支付范围限定","配伍禁忌"],
                       干预=["结算前人工复核"], 可用性="可用-确定性最强",
                       备注="本矩阵中唯一可在事前硬拦截的单元格，因其为确定性判定"),
 ("事前","物流"): dict(信号=[], 干预=[], 可用性="**不可用**",
                       备注="药品尚未流转，无物流数据。此单元格为空是数据事实，非待补"),

 ("事中","医院"): dict(信号=["实时费用累计超预算进度"], 干预=["预警"], 可用性="可用", 备注=""),
 ("事中","医师"): dict(信号=["本次处方与备案病种目录不符"],
                       干预=["开具时拦截"], 可用性="可用",
                       备注="对标方案中慢病标准诊疗路径的核心机制：与备案病种不符即拦"),
 ("事中","患者"): dict(信号=["本次就诊与历史画像冲突"], 干预=["提示"], 可用性="可用", 备注=""),
 ("事中","药品"): dict(信号=["强制管控药品","特殊药品"],
                       干预=["智能拦截+全程留痕"], 可用性="可用",
                       备注="对标方案明确提到的特殊药品事中审核"),
 ("事中","物流"): dict(信号=["发药与处方不符"], 干预=["发药环节核验"], 可用性="可用", 备注=""),

 ("事后","医院"): dict(信号=["重复收费/超标准收费/分解项目收费"],
                       干预=["协议处理","追回"], 可用性="可用-优先级最高",
                       备注="OFFICIAL 此三类合计约占全部违法违规使用基金问题的36%"),
 ("事后","医师"): dict(信号=["处方-检验-诊断三者不一致"], 干预=["专项通报","整改"],
                       可用性="可用", 备注="对标方案中月度AI分析报告的通报机制"),
 ("事后","患者"): dict(信号=["群体刷卡聚集","医患共谋二部图异常"],
                       干预=["暂停结算资格","报送监管部门"], 可用性="可用",
                       备注="**须人工审定，模型不得自动执行**"),
 ("事后","药品"): dict(信号=["购药量与适应症日剂量严重背离"], 干预=["追回"], 可用性="可用", 备注=""),
 ("事后","物流"): dict(信号=["药品追溯码流向异常","回流药"],
                       干预=["立案"], 可用性="可用-倒药唯一可证实环节",
                       备注="OFFICIAL 全国已归集药品追溯码超1000亿条；"
                            "处方/剂量/适应症全部合规的药同样可被倒卖，"
                            "只有流向数据能证实倒药"),
}


def cell(stage: str, obj: str):
    c = dict(MATRIX[(stage, obj)])
    c["证据门槛"] = THRESHOLD[stage]
    c["可逆性"] = REVERSIBILITY[stage]
    return c


def coverage_report():
    rows = []
    for s in STAGES:
        for o in OBJECTS:
            c = cell(s, o)
            rows.append(dict(时点=s, 对象=o, 可用性=c["可用性"],
                             证据门槛=c["证据门槛"], 可逆性=c["可逆性"],
                             信号数=len(c["信号"]), 干预=";".join(c["干预"]) or "—"))
    return rows


def audit_thresholds():
    """校验门槛梯度未被破坏——这是本模块的不变量。"""
    assert THRESHOLD["事前"] > THRESHOLD["事中"] > THRESHOLD["事后"], \
        "证据门槛梯度被破坏：事前门槛必须严格高于事中高于事后"
    empty = [k for k, v in MATRIX.items() if v["可用性"].startswith("**不可用")]
    return dict(梯度校验="通过", 空单元格=[f"{s}×{o}" for s, o in empty],
                单元格总数=len(MATRIX), 可用=len(MATRIX) - len(empty))

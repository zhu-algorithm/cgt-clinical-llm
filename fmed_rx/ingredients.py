"""通用名/商品名/复方制剂 → 活性成分归一。

归集是超量用药判定的真正难点：同一成分可能以不同商品名、
不同通用名写法、或作为复方制剂的一个组分出现在多张处方上。
不先归一到成分，剂量累加就是错的。
"""
from __future__ import annotations

# 商品名 → 通用名（示例种子，真实部署须由药品本位码/国家药品编码表生成）
BRAND_TO_GENERIC = {
    "亚莫利": "格列美脲", "万苏平": "格列美脲",
    "拜唐苹": "阿卡波糖", "卡博平": "阿卡波糖",
    "格华止": "二甲双胍", "美迪康": "二甲双胍",
    "络活喜": "氨氯地平", "норваск": "氨氯地平",
    "代文": "缬沙坦", "倍他乐克": "美托洛尔",
    "立普妥": "阿托伐他汀", "可定": "瑞舒伐他汀",
}

# 复方制剂 → [(成分, 单片含量mg), ...]
# 复方制剂是漏判超量的主要通道：医生开了复方，单看通用名查不到该成分。
COMPOUND_DECOMPOSE = {
    "二甲双胍格列本脲片(I)": [("二甲双胍", 250.0), ("格列本脲", 1.25)],
    "二甲双胍格列本脲片(II)": [("二甲双胍", 500.0), ("格列本脲", 2.5)],
    "缬沙坦氨氯地平片(I)": [("缬沙坦", 80.0), ("氨氯地平", 5.0)],
    "氯沙坦钾氢氯噻嗪片": [("氯沙坦钾", 50.0), ("氢氯噻嗪", 12.5)],
    "复方利血平氨苯蝶啶片": [("利血平", 0.1), ("氨苯蝶啶", 12.5),
                              ("氢氯噻嗪", 12.5), ("硫酸双肼屈嗪", 12.5)],
}

# 同义写法归一
ALIAS = {
    "盐酸二甲双胍": "二甲双胍", "二甲双胍盐酸盐": "二甲双胍",
    "苯磺酸氨氯地平": "氨氯地平", "马来酸氨氯地平": "氨氯地平",
    "酒石酸美托洛尔": "美托洛尔", "琥珀酸美托洛尔": "美托洛尔",
    "阿托伐他汀钙": "阿托伐他汀",
}


def to_generic(name: str) -> str:
    n = name.strip()
    n = BRAND_TO_GENERIC.get(n, n)
    for k, v in ALIAS.items():
        if n.startswith(k):
            return v
    return n


def decompose(name: str, n_units: float, strength_mg: float | None):
    """返回 [(成分, 该次处方该成分总mg)]。复方制剂按单片含量拆分。"""
    n = name.strip()
    if n in COMPOUND_DECOMPOSE:
        return [(ing, mg * n_units) for ing, mg in COMPOUND_DECOMPOSE[n]]
    g = to_generic(n)
    if strength_mg is None:
        return [(g, float("nan"))]
    return [(g, strength_mg * n_units)]
